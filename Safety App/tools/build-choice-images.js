/* Registers the per-scene / per-answer pictures saved under img/choices/.
   Writes js/choice-images.js (a list the app checks, so it never requests a
   picture that doesn't exist). Run after adding or removing pictures:
       node tools/build-choice-images.js
   File names come from reports/Safety-Superheroes-Image-Prompts.xlsx, e.g.
   img/choices/fire-safety/L1-S02-C1.webp  (.webp, .png, .jpg or .jpeg). */
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const dir = path.join(root, 'img', 'choices');
const OK = /^(L\d+-S\d{2}-(?:C\d+|scene))\.(webp|png|jpe?g)$/i;
const PREF = ['webp', 'jpg', 'jpeg', 'png'];

const map = {};
let skipped = [];
if (fs.existsSync(dir)){
  for (const topic of fs.readdirSync(dir).sort()){
    const tdir = path.join(dir, topic);
    if (!fs.statSync(tdir).isDirectory()) continue;
    for (const f of fs.readdirSync(tdir).sort()){
      const m = OK.exec(f);
      if (!m){ skipped.push(`${topic}/${f}`); continue; }
      const key = `${topic}/${m[1]}`;
      const ext = m[2].toLowerCase();
      const prev = map[key];
      if (!prev || PREF.indexOf(ext) < PREF.indexOf(prev.split('.').pop())) map[key] = `img/choices/${topic}/${f}`;
    }
  }
}
const out = `/* GENERATED by tools/build-choice-images.js -- do not edit by hand.
   Pictures saved in img/choices/ for individual story scenes and answers. */
const CHOICE_IMAGES = ${JSON.stringify(map, null, 1)};
`;
fs.writeFileSync(path.join(root, 'js', 'choice-images.js'), out);
console.log(`Registered ${Object.keys(map).length} picture(s) in js/choice-images.js`);
if (skipped.length) console.log('Skipped (name does not match the sheet):\n  ' + skipped.join('\n  '));
